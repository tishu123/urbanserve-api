-- Professionals are now assigned by urbanserve-dispatch (shift + availability aware) after booking.
-- provider_id becomes the customer's *preferred* professional (optional); the assigned one is
-- stored as a snapshot when dispatch replies, since dispatch's roster can include pros this
-- service doesn't list.
alter table booking alter column provider_id drop not null;
alter table booking add column city                   varchar(80);
alter table booking add column assigned_provider_id   bigint;
alter table booking add column assigned_provider_name varchar(120);
alter table booking add column assigned_provider_phone varchar(20);
alter table booking add column assigned_provider_rating double precision;
alter table booking add column arrival_window_start   timestamp;
alter table booking add column arrival_window_end     timestamp;
alter table booking add column status_reason          varchar(300);
alter table booking add column version                bigint not null default 0;

-- Transactional outbox: a message is written in the same transaction as the booking change and
-- sent by OutboxRelay afterwards, so no message is lost if SQS is briefly unreachable.
create table outbox_event (
    id          bigint generated by default as identity primary key,
    topic       varchar(60)  not null,
    message_key varchar(60)  not null,
    payload     text         not null,
    created_at  timestamp    not null,
    sent_at     timestamp,
    attempts    int          not null default 0,
    last_error  varchar(500)
);
create index idx_outbox_unsent on outbox_event (sent_at, id);
