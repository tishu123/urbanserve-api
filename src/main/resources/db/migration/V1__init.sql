-- Works on PostgreSQL and on H2 (MODE=PostgreSQL) for local dev.
create table service_category (
    id          bigint generated by default as identity primary key,
    name        varchar(120)     not null,
    description varchar(500),
    base_price  double precision not null
);

create table provider (
    id          bigint generated by default as identity primary key,
    name        varchar(120)     not null,
    phone       varchar(20)      not null,
    city        varchar(80)      not null,
    rating      double precision not null default 0,
    category_id bigint           not null references service_category (id)
);
create index idx_provider_category on provider (category_id);

create table booking (
    id             bigint generated by default as identity primary key,
    customer_name  varchar(120) not null,
    customer_phone varchar(20)  not null,
    address        varchar(500) not null,
    scheduled_at   timestamp    not null,
    created_at     timestamp    not null,
    status         varchar(20)  not null,
    category_id    bigint       not null references service_category (id),
    provider_id    bigint       not null references provider (id)
);
create index idx_booking_phone on booking (customer_phone, scheduled_at);

create table otp_challenge (
    id         bigint generated by default as identity primary key,
    phone      varchar(20) not null,
    code_hash  varchar(64) not null,
    created_at timestamp   not null,
    expires_at timestamp   not null,
    attempts   int         not null default 0,
    consumed   boolean     not null default false
);
create index idx_otp_phone_created on otp_challenge (phone, created_at);
