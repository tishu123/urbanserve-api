-- Rohnit: Add the backend-managed service package catalogue.
-- Package prices are calculated using the category base price and package factor.

CREATE TABLE service_package (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id  BIGINT NOT NULL REFERENCES service_category(id),
    code         VARCHAR(80) NOT NULL,
    name         VARCHAR(120) NOT NULL,
    price_factor DECIMAL(10,4) NOT NULL,
    active       BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT uk_service_package_category_code
        UNIQUE (category_id, code),

    CONSTRAINT chk_service_package_price_factor
        CHECK (price_factor > 0)
);

CREATE INDEX idx_service_package_category_active
    ON service_package(category_id, active);